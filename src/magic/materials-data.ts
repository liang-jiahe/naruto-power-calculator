export type MaterialCost = {
  greenWater: number
  purpleStar: number
  protectionCharm: number
}

export type MaterialEntry = MaterialCost & { level: number }
export type MaterialSeries = {
  name: string
  maxLevel: number
  entries: readonly MaterialEntry[]
}

const createSeries = (name: string, rows: readonly [number, number, number, number][]): MaterialSeries => Object.freeze({
  name,
  maxLevel: rows[rows.length - 1][0],
  entries: Object.freeze(rows.map(([level, greenWater, purpleStar, protectionCharm]) => Object.freeze({
    level,
    greenWater,
    protectionCharm,
    purpleStar
  })))
});

